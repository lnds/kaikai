#!/usr/bin/env python3
"""Generate stage2/runtime/runtime_llvm_decls.h: the declarations of every `kaix_*`
entry point stage0/runtime_llvm.c defines, so a separately compiled
translation unit can call the runtime without including its definitions.

A leaf op outside the `!KAI_HOT_ONLY` blocks whose body is a single
`return` expression is emitted as `static inline`, so the unit inlines it;
every other entry point is a prototype resolved against the runtime owner.

Usage: gen-runtime-decls.py [--check]
"""
import os
import re
import sys

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
SRC = os.path.join(ROOT, "stage0", "runtime_llvm.c")
OUT = os.path.join(ROOT, "stage2", "runtime", "runtime_llvm_decls.h")

DEF = re.compile(r'^([A-Za-z_][^\n;{}=#]*?\b(kaix_\w+)\s*\(((?:[^()]|\([^()]*\))*)\))\s*\{(.*)$')
THUNK = re.compile(r'^KAIX_CORE_THUNK\d\((\w+)\)')
COLD = re.compile(r'^#\s*if\s+!defined\(KAI_HOT_ONLY\)')
IF = re.compile(r'^#\s*if')
ENDIF = re.compile(r'^#\s*endif')
MACRO_USE = re.compile(r'\b[A-Z][A-Z0-9_]{2,}\b')
ONE_LINER = re.compile(r'^\s*[^{}]*;\s*\}\s*(/\*.*\*/)?\s*$')


OPEN_SIG = re.compile(r'^[A-Za-z_][^;{}=#]*\bkaix_\w+\s*\((?:[^()]|\([^()]*\))*$')


def join_signatures(text):
    out = []
    pending = None
    for line in text.split("\n"):
        if pending is not None:
            pending += " " + line.strip()
            if ")" in line:
                out.append(pending)
                pending = None
        elif OPEN_SIG.match(line):
            pending = line
        else:
            out.append(line)
    return out


LOCAL_DEFINE = re.compile(r'^#\s*define\s+(\w+)')
STATIC_NAME = re.compile(r'^static\b[^;{=]*?\b(\w+)\s*(?:\(|\[|=|;)')
WORD = re.compile(r'\b\w+\b')


def local_names(lines):
    names = set()
    for line in lines:
        m = LOCAL_DEFINE.match(line)
        if m:
            names.add(m.group(1))
            continue
        m = STATIC_NAME.match(line)
        if m:
            names.add(m.group(1))
    return names


def inlinable(body, names):
    if "static " in body or "__thread" in body or "setjmp" in body or "alloca" in body:
        return False
    if "kai_core_" in body:
        return False
    return not any(w in names for w in WORD.findall(body))


def render(text):
    lines_in = join_signatures(text)
    names = local_names(lines_in)
    protos = {}
    bodies = {}
    depth = 0
    cold = []
    i = 0
    while i < len(lines_in):
        line = lines_in[i]
        i += 1
        if COLD.match(line):
            depth += 1
            cold.append(depth)
            continue
        if IF.match(line):
            depth += 1
            continue
        if ENDIF.match(line):
            if cold and cold[-1] == depth:
                cold.pop()
            depth -= 1
            continue
        m = DEF.match(line)
        if m:
            sig = " ".join(m.group(1).split())
            if sig.startswith(("static", "return")):
                continue
            name = m.group(2)
            rest = m.group(4)
            protos[name] = sig + ";"
            if depth != 0 or cold:
                continue
            if ONE_LINER.match(rest):
                body = "{" + rest.strip()
            elif rest.strip() == "":
                j = i
                while j < len(lines_in) and lines_in[j] != "}":
                    j += 1
                body = "{\n" + "\n".join(lines_in[i:j]) + "\n}"
                i = j + 1
            else:
                continue
            if inlinable(body, names):
                bodies[name] = body
            continue
        t = THUNK.match(line)
        if t:
            protos["kaix_%s_thunk" % t.group(1)] = "KaiValue *kaix_%s_thunk(KaiValue *s, KaiValue **a, int n);" % t.group(1)
    out = [
        "/* Generated by tools/gen-runtime-decls.py from runtime_llvm.c; do not edit. */",
        "#ifndef KAI_RUNTIME_LLVM_DECLS_H",
        "#define KAI_RUNTIME_LLVM_DECLS_H",
        "#include <runtime.h>",
    ]
    for k in sorted(protos):
        out.append(("static inline " + protos[k].replace("KAI_RT_SHARED ", "") if k in bodies else protos[k]))
    for k in sorted(bodies):
        sig = protos[k][:-1].replace("KAI_RT_SHARED ", "")
        out.append("static inline " + sig + " " + bodies[k])
    out.append("#endif")
    return "\n".join(out) + "\n"


def main():
    out = render(open(SRC).read())
    if "--check" in sys.argv:
        cur = open(OUT).read() if os.path.exists(OUT) else ""
        if cur != out:
            sys.stderr.write("stage2/runtime/runtime_llvm_decls.h is stale; run tools/gen-runtime-decls.py\n")
            return 1
        return 0
    open(OUT, "w").write(out)
    return 0


sys.exit(main())
