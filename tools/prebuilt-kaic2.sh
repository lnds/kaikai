#!/usr/bin/env bash
# prebuilt-kaic2.sh — one kaic2 build per commit, shared by every worktree of the repo.
#
#   tools/prebuilt-kaic2.sh build [<ref>]    build kaic2 + bin/kai at <ref> (default origin/main)
#                                            once, native-capable where llvm-config is found,
#                                            and store it by commit
#   tools/prebuilt-kaic2.sh seed [<worktree>] give a worktree (default .) the build of the commit
#                                            it branched from origin/main at, building it first
#                                            when missing; local commits on top are rebuilt by
#                                            `make kaic2-fast` (C backend only)
#   tools/prebuilt-kaic2.sh has [<ref>]      exit 0 iff a build of <ref> is stored for the release
#                                            that would boot it now
#   tools/prebuilt-kaic2.sh path [<ref>]     print the stored build's root, building it first when
#                                            missing; <root>/bin/kai runs on its own
#
# Store: $KAI_PREBUILT_STORE, else ${XDG_CACHE_HOME:-~/.cache}/kaikai-prebuilt; the newest
# $KAI_PREBUILT_KEEP (default 3) builds are kept. A build is keyed by <sha>-<boot release>,
# since the same source booted from another release is another binary, and is stored only at
# the self-host fixed point (one more hop reproduces its C). Entries keyed by the sha alone
# are never looked up; they age out.
set -eu

REPO="$(dirname "$(git rev-parse --path-format=absolute --git-common-dir)")"
STORE="${KAI_PREBUILT_STORE:-${XDG_CACHE_HOME:-$HOME/.cache}/kaikai-prebuilt}"
KEEP="${KAI_PREBUILT_KEEP:-3}"
# In dependency order: touch_chain relies on it.
FILES=(
  stage0/runtime_llvm.bc stage0/runtime_llvm.bc.stamp stage0/runtime_inline.bc
  stage2/build/stage2.c stage2/build/stage2.c.id stage2/kaic2 stage2/build/kaic2.id
  bin/kai
)

# The tracked files bin/kai resolves its dev layout against.
STANDALONE=(stage0 stage2/runtime.h stage2/runtime stdlib tools/kai/plugins VERSION EDITION)

die() { echo "prebuilt-kaic2: $*" >&2; exit 2; }
sha_of() { git -C "$REPO" rev-parse --verify "${1:-origin/main}^{commit}"; }

# The release that boots <sha> now, e.g. v0.169.0-darwin-arm64.
boot_tag() { # sha
  local root="$STORE/bootroot" id
  mkdir -p "$root"
  git -C "$REPO" show "$1:VERSION" >"$root/VERSION"
  id="$(KAIC_BOOT_ROOT="$root" "$(dirname "$0")/kaic-boot.sh" release-id 2>/dev/null)" || return 1
  id="${id%% *}"
  echo "${id#kaikai-}"
}

key_of() { # ref -> <sha>-<boot release>
  local sha tag
  sha="$(sha_of "${1:-origin/main}")"
  tag="$(boot_tag "$sha")" || die "cannot resolve the release that boots ${sha:0:12}"
  echo "$sha-$tag"
}
stored() { ls -1td "$STORE"/*/ 2>/dev/null | grep -vE '/(tree|lock|bootroot)/$|\.tmp/$' || true; }

copy_files() { # from-root to-root
  local f
  for f in "${FILES[@]}"; do
    [ -e "$1/$f" ] || continue
    mkdir -p "$2/$(dirname "$f")"
    cp -p "$1/$f" "$2/$f"
  done
}

# A stored root is a dev layout of its commit: bin/kai finds stage0/, stdlib/ and stage2/kaic2
# beside it. Idempotent, so a build stored before the layout existed is completed in place.
complete_layout() { # key
  [ -d "$STORE/$1/stdlib" ] && return 0
  git -C "$REPO" archive "${1%%-*}" "${STANDALONE[@]}" | tar -x -C "$STORE/$1"
}

# Copies land with arbitrary mtimes relative to the checkout: touch the chain
# `make kaic2` consults, inputs first, so every target is newer than its inputs.
touch_chain() {
  local f
  for f in "${FILES[@]}"; do
    [ -e "$1/$f" ] && { touch "$1/$f"; sleep 1; }
  done
}

# Prints the env assignments that make llvm-config (and, on macOS, its libraries) visible.
llvm_env() {
  local d
  command -v llvm-config >/dev/null && return 0
  for d in /opt/homebrew/opt/llvm/bin /usr/local/opt/llvm/bin; do
    [ -x "$d/llvm-config" ] || continue
    echo "PATH=$d:$PATH"
    echo "LIBRARY_PATH=${d%/opt/llvm/bin}/lib${LIBRARY_PATH:+:$LIBRARY_PATH}"
    return 0
  done
  return 1
}

# One build at a time per store: concurrent seeds of a missing commit wait for the first.
with_lock() {
  mkdir -p "$STORE"
  until mkdir "$STORE/lock" 2>/dev/null; do sleep 5; done
  trap 'rmdir "$STORE/lock" 2>/dev/null' EXIT
  "$@"
  rmdir "$STORE/lock"; trap - EXIT
}

cmd_build() {
  git -C "$REPO" fetch -q origin
  with_lock build_locked "$(key_of "${1:-origin/main}")"
}

# One more hop of the built kaic2 over its own source must emit the C it was linked from.
fixed_point() { # tree
  local form="" out="$1/stage2/build/fixed-point.c" rc
  head -n 1 "$1/stage2/build/stage2.c" | grep -q '^/\* generated by kaikai stage 2 \*/' || form=--emit=c-modular
  (cd "$1/stage2" && KAIKAI_STDLIB_PATH="$1/stdlib" ./kaic2 $form --edition "$(cat "$1/EDITION")" main.kai) >"$out" \
    && cmp -s "$out" "$1/stage2/build/stage2.c"
  rc=$?
  rm -f "$out"
  return $rc
}

build_locked() {
  local key="$1" sha="${1%%-*}" tree out env=() native=0 line
  [ -x "$STORE/$key/stage2/kaic2" ] && { complete_layout "$key"; echo "prebuilt-kaic2: $key already stored"; return 0; }
  if out="$(llvm_env)"; then
    native=1
    while IFS= read -r line; do [ -n "$line" ] && env+=("$line"); done <<<"$out"
  fi
  tree="$STORE/tree"
  mkdir -p "$STORE"
  if [ -e "$tree/.git" ]; then
    git -C "$tree" checkout -q --detach "$sha"
  else
    git -C "$REPO" worktree prune
    git -C "$REPO" worktree add -q --detach "$tree" "$sha"
  fi
  rm -f "$tree/stage2/kaic2"
  rm -f "$tree/stage2/build/stage2.c.id"
  (cd "$tree" && env ${env[@]+"${env[@]}"} make KAI_LLVM=$native kaic2 bin/kai) >"$STORE/build-$key.log" 2>&1 \
    || die "build of $key failed; see $STORE/build-$key.log"
  grep -q "^boot=release kaikai-${key#*-} " "$tree/stage2/build/kaic2.id" \
    || die "$key was booted from $(sed -n 's/^boot=//p' "$tree/stage2/build/kaic2.id" | cut -d' ' -f1-2)"
  fixed_point "$tree" || die "$key is not at the self-host fixed point: one more hop emits different C"
  rm -rf "$STORE/$key.tmp"
  copy_files "$tree" "$STORE/$key.tmp"
  git -C "$REPO" archive "$sha" "${STANDALONE[@]}" | tar -x -C "$STORE/$key.tmp"
  mv "$STORE/$key.tmp" "$STORE/$key"
  stored | tail -n +$((KEEP + 1)) | while IFS= read -r d; do rm -rf "$d"; done
  rm -f "$STORE/build-$key.log"
  echo "prebuilt-kaic2: stored $key ($([ $native = 1 ] && echo native-capable || echo C backend only), fixed point verified)"
}

# An older commit's kaic2 may not compile a newer tree, so a worktree is seeded only
# from the build of its own base commit.
cmd_seed() {
  local wt="${1:-.}" head base key
  head="$(git -C "$wt" rev-parse HEAD)"
  git -C "$REPO" fetch -q origin
  base="$(git -C "$wt" merge-base HEAD origin/main)"
  key="$(key_of "$base")"
  [ -x "$STORE/$key/stage2/kaic2" ] || with_lock build_locked "$key"
  copy_files "$STORE/$key" "$wt"
  touch_chain "$wt"
  if [ "$head" = "$base" ]; then
    echo "prebuilt-kaic2: restored the build of $base"
  else
    (cd "$wt" && make kaic2-fast bin/kai >/dev/null)
    echo "prebuilt-kaic2: restored the build of $base and rebuilt local commits by kaic2-fast (C backend only)"
  fi
}

case "${1:-}" in
  build) shift; cmd_build "$@" ;;
  seed)  shift; cmd_seed "$@" ;;
  path)  shift; key="$(key_of "${1:-origin/main}")"
         [ -x "$STORE/$key/stage2/kaic2" ] || with_lock build_locked "$key" >&2
         complete_layout "$key"; echo "$STORE/$key" ;;
  has)   shift; key="$(key_of "${1:-origin/main}" 2>/dev/null)" && [ -x "$STORE/$key/stage2/kaic2" ] ;;
  *) sed -n '2,16p' "$0"; exit 2 ;;
esac
